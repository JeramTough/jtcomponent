public enum TreeNode3SortMethod {

    /**
     * 以 orderWithLevel 为基准，升序（数值越小越靠前）
     */
    ASCENDING,

    /**
     * 以 orderWithLevel 为基准，降序（数值越大越靠前）
     */
    DESCENDING;
}
